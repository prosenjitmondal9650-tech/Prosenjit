create table if not exists public.nifty_recorder_shift_history (
  event_key text primary key,
  event_date date not null,
  event_time text,
  side text not null check (side in ('call', 'put')),
  status text,
  direction text,
  source text,
  from_level numeric,
  to_level numeric,
  changed boolean default false,
  expiry text,
  raw_event jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists nifty_shift_history_date_idx
  on public.nifty_recorder_shift_history (event_date desc, side);

create table if not exists public.nifty_recorder_snapshots (
  id bigint generated by default as identity primary key,
  snapshot_time timestamptz not null,
  event_date date not null,
  expiry text,
  market_open boolean,
  nifty jsonb not null default '{}'::jsonb,
  atm numeric,
  support jsonb,
  resistance jsonb,
  level_analysis jsonb not null default '{}'::jsonb,
  rows jsonb not null default '[]'::jsonb,
  websocket jsonb,
  last_update text,
  greeks_update text,
  greeks_count bigint default 0,
  tick_count bigint default 0,
  raw_ws_messages bigint default 0,
  last_nifty_tick_at double precision default 0,
  last_option_tick_at double precision default 0,
  created_at timestamptz not null default now()
);

create index if not exists nifty_snapshots_date_time_idx
  on public.nifty_recorder_snapshots (event_date desc, snapshot_time desc);

alter table public.nifty_recorder_shift_history enable row level security;
alter table public.nifty_recorder_snapshots enable row level security;
