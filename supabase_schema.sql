-- Run in Supabase SQL Editor before enabling the cloud recorder.
-- The Python app writes JSON payload columns as jsonb.

create table if not exists public.nifty_recorder_snapshots (
  id bigint generated by default as identity primary key,
  snapshot_time timestamptz not null,
  event_date date,
  expiry text,
  market_open boolean,
  nifty jsonb not null default '{}'::jsonb,
  atm jsonb,
  support jsonb,
  resistance jsonb,
  level_analysis jsonb not null default '{}'::jsonb,
  rows jsonb not null default '[]'::jsonb,
  websocket text,
  last_update text,
  greeks_update text,
  greeks_count bigint default 0,
  tick_count bigint default 0,
  raw_ws_messages bigint default 0,
  last_nifty_tick_at double precision default 0,
  last_option_tick_at double precision default 0
);
create index if not exists nifty_recorder_snapshots_time_idx
  on public.nifty_recorder_snapshots (snapshot_time desc, id desc);

create table if not exists public.nifty_recorder_shift_history (
  id bigint generated by default as identity primary key,
  event_key text not null unique,
  event_date date not null,
  event_time text,
  side text not null,
  status text,
  direction text,
  source text,
  from_level jsonb,
  to_level jsonb,
  changed boolean default false,
  expiry text,
  raw_event jsonb not null default '{}'::jsonb
);
create index if not exists nifty_recorder_shift_history_date_idx
  on public.nifty_recorder_shift_history (event_date desc, side);

